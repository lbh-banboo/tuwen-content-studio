"""平台层：与业务无关、所有模块共用的基础设施。

含四件事，职责边界如下：

- `configuration` —— 配置读取。凭据只从环境变量来，无默认值。
- `errors`        —— 错误码体系、统一响应包装、details 脱敏、异常处理器。
- `pagination`    —— 不透明游标分页，绑定排序与筛选条件。
- `database`      —— engine 管理、探针、超时注入。

**为什么单独成层而不是塞进各业务模块**：
四个业务模块（projects/contents/knowledge/review…）都要用这四件事。
若各自实现，会出现"项目模块的 404 有 code、内容模块的 404 没有"这类不一致，
而契约要求错误体形状唯一。抽出平台层，让"响应形状只有一处定义"成为结构保证。

**依赖方向**：业务模块 → 平台层，绝不反向。平台层不 import 任何 modules.*。
"""