"""领域事件的存储模型（WP14）。

按数据结构文档 02 §11 的 `domain_events` 建表。

**这张表是 SSE 的"真相层"**（ADR-14 的三层机制之一）：

> | 真相层 | 事件的唯一持久化来源 | `domain_events` 表落库，含自增序列号（用于 Last-Event-ID） |

**为什么"真相"必须在数据库里而不是在推送通道里**：ADR-14 明写 PG 的
`NOTIFY` 是 **at-most-once** —— 通知可能丢，且丢了不会有人告诉你。
如果事件只存在于通知里，那么"丢通知"就等于"用户永远看不到这条进度"，
而且**没有任何机制能发现**。落库之后，通知只负责"快"，补漏负责"全"，
两者合起来才是"必达"。

**`sequence` 为什么必须是全局自增（bigint）而不是按项目编号**：
协议 §11 明写"**不假设全局 ID 连续等于本项目连续**"—— 这句话反过来
确认了它是全局的。前端拿到 `id: 18492` 只当作"位置标记"用（重连时带回来），
不能用来判断"本项目的事件有没有跳号"。

**`sequence` 为什么用 `bigint` 而不是 `int`**：它是全系统所有事件共用的计数器，
按"20 在线 / 50 成员"的规模，一年内到不了 21 亿；但**一旦溢出就是灾难**
（事件写不进去、SSE 全挂）。bigint 的存储代价可以忽略。
另外注意协议 §1："所有数据库 bigint 对外固定为十进制字符串"——
`sequence` 出现在 SSE 的 `id:` 行与 `data.sequence` 里，**都是字符串**。

**`project_id` 可空**：平台级事件（如 `knowledge.indexReady` 的全员通知）
不属于任何项目。它的可见范围由 `service.can_view_event` 决定（登记 OP-112）。

**本表刻意没有 `updated_at`**：事件是追加的，写完就不改
（与 WP11 的 `version_nodes` 同一判断：加了它反而暗示"会被改"）。
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Final

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    Index,
    Integer,
    String,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column

from rednote.platform.base import Base, created_at_column, uuid_pk

# 事件体 schema 版本。与 Outbox 的做法一致：写入方带上它，
# 消费方据此选择解析方式（将来 payload 结构演进时，老事件仍能被正确解读）。
EVENT_SCHEMA_VERSION: Final[int] = 1

# ---------------------------------------------------------------------------
# 事件类型（协议 §11 逐条照抄，不多不少）
#
# 协议原文：
# > 事件类型：job.queued、job.progress、job.completed、job.failed、
# > content.reviewRequired、project.assignmentChanged、knowledge.indexReady、
# > metrics.updated、budget.warning、sync.required。
# ---------------------------------------------------------------------------

EVENT_JOB_QUEUED: Final[str] = "job.queued"
EVENT_JOB_PROGRESS: Final[str] = "job.progress"
EVENT_JOB_COMPLETED: Final[str] = "job.completed"
EVENT_JOB_FAILED: Final[str] = "job.failed"
EVENT_CONTENT_REVIEW_REQUIRED: Final[str] = "content.reviewRequired"
EVENT_PROJECT_ASSIGNMENT_CHANGED: Final[str] = "project.assignmentChanged"
EVENT_KNOWLEDGE_INDEX_READY: Final[str] = "knowledge.indexReady"
EVENT_METRICS_UPDATED: Final[str] = "metrics.updated"
EVENT_BUDGET_WARNING: Final[str] = "budget.warning"
EVENT_SYNC_REQUIRED: Final[str] = "sync.required"

EVENT_TYPES: Final[frozenset[str]] = frozenset(
    {
        EVENT_JOB_QUEUED,
        EVENT_JOB_PROGRESS,
        EVENT_JOB_COMPLETED,
        EVENT_JOB_FAILED,
        EVENT_CONTENT_REVIEW_REQUIRED,
        EVENT_PROJECT_ASSIGNMENT_CHANGED,
        EVENT_KNOWLEDGE_INDEX_READY,
        EVENT_METRICS_UPDATED,
        EVENT_BUDGET_WARNING,
        EVENT_SYNC_REQUIRED,
    }
)

EVENT_TYPE_LIST_SQL: Final[str] = ", ".join(
    f"'{name}'" for name in sorted(EVENT_TYPES)
)

# `jobId` 是协议 §11 事件体里的字段（"jobId":"job-01"）。它必须单独一列：
#   · 前端收到 job.progress 后要按 jobId 归位到某个进度条 —— 从 payload 里挖
#     会让"能不能正确渲染"取决于各产生方记得把 jobId 放进 payload；
#   · 排障时"这个任务发了哪些事件"是最常见的查询，有列就能建索引。
# 数据结构 §11 的列清单里没有它 → 已登记为 OP-110。
#
# 协议 §11 的事件体里还提到的字段各自落在哪：
#   schemaVersion → 独立列；projectId → 独立列；sequence → 独立列；
#   occurredAt → 独立列；payload → 独立列；event（SSE 的 event: 行）→ 独立列。
# 唯独 jobId 没有列，因此补这一列而不是把它塞进 payload。
AGGREGATE_KINDS: Final[frozenset[str]] = frozenset(
    {"job", "content", "project", "knowledge", "metrics", "budget", "system"}
)


class DomainEvent(Base):
    """一条可推送的领域事件。

    **只含界面必要信息**（数据结构 §11 原文）。协议 §11 进一步约束：

    > 事件数据不带 Prompt、Brief 全文、外部密钥或其他项目对象。

    这条不是"注意一下"就能守住的 —— 它取决于**产生事件的调用方**传了什么。
    因此写入路径上做一层校验（`service.publish_event`），
    命中敏感键名或超长文本即**拒绝写入**。理由：事件一旦落库又被推给
    错误的人，就无法撤回；在入口拒绝比事后过滤可靠。
    """

    __tablename__ = "domain_events"

    id: Mapped[uuid.UUID] = uuid_pk()

    # 全局自增序列号，作为 SSE 的 `id:` 与 Last-Event-ID 的取值来源。
    #
    # **为什么不用 UUID 做主键兼做序列**：Last-Event-ID 的补漏查询是
    # `sequence > last`，需要**可比较、单调**的值。UUID 不可比。
    # 因此保留 UUID 主键（与全库一致）另加一个自增列。
    #
    # **必须用 `Identity`**：`autoincrement=True` 只在"该列是主键"或
    # "该列是唯一的整数列"时才让 SQLAlchemy 生成序列 —— 而本表主键是 UUID，
    # 于是 DDL 会渲染成**裸 `BIGINT NOT NULL`（没有 DEFAULT、没有序列）**，
    # 插入时不显式给值就 `NOT NULL` 违约，整个 SSE 都拿不到 `id`。
    # 本机实测确认过这个渲染结果。
    # `Identity` 是 SQL 标准写法（PG 10+ 支持 `GENERATED BY DEFAULT AS IDENTITY`），
    # 比 `Sequence` 对象更贴近 DDL，autogenerate 处理也更干净。
    sequence: Mapped[int] = mapped_column(
        BigInteger, Identity(always=False), nullable=False, unique=True
    )

    # 平台级事件可空（见模块 docstring）。
    project_id: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("projects.id", ondelete="RESTRICT"),
        nullable=True,
    )
    # 发起人。可空：系统自动产生的事件（如索引就绪）没有具体操作人。
    actor_id: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=True,
    )

    event_type: Mapped[str] = mapped_column(String(60), nullable=False)
    aggregate_id: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True), nullable=True
    )
    # 协议 §11 事件体里的 `jobId`。可空：非任务类事件没有它。
    job_id: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True), nullable=True
    )

    schema_version: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text(str(EVENT_SCHEMA_VERSION))
    )
    payload: Mapped[dict] = mapped_column(
        JSONB, nullable=False, server_default=text("'{}'::jsonb")
    )

    # 事件**发生**的时间（业务时间）。与 `created_at`（落库时间）分开：
    # 两者通常相差毫秒，但排障时"事件什么时候发生的"与"什么时候写进来的"
    # 是两个不同的问题，合并成一列就永远分不出来了。
    occurred_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=text("now()")
    )
    created_at: Mapped[datetime] = created_at_column()

    __table_args__ = (
        CheckConstraint(
            f"event_type IN ({EVENT_TYPE_LIST_SQL})", name="event_type_valid"
        ),
        CheckConstraint("schema_version >= 1", name="schema_version_positive"),
        CheckConstraint("sequence > 0", name="sequence_positive"),
        # 补漏查询的主路径：`WHERE sequence > :last ORDER BY sequence`。
        # sequence 上的 UNIQUE 约束已经建了索引（见列定义），
        # 这里再按 project 建一条，供"按 projectId 订阅时的初始补齐"用。
        Index("ix_domain_events_project_sequence", "project_id", "sequence"),
        # 排障路径："这个任务发了哪些事件"。
        Index("ix_domain_events_job", "job_id"),
        Index("ix_domain_events_created_at", "created_at"),
    )


